#!/usr/bin/env bash
# ==============================================================================
# volatility3_triage.sh — PurpleForge Automated Memory Forensic Triage
#
# Runs Volatility3 plugins against physical memory dumps acquired by Velociraptor:
#   1. windows.pslist   - Active process listing
#   2. windows.pstree   - Parent-child process hierarchy
#   3. windows.cmdline  - Process execution arguments and command-line flags
#   4. windows.malfind  - Injected code, hidden DLLs, and memory permissions (PAGE_EXECUTE_READWRITE)
#   5. windows.netscan  - Active and closed TCP/UDP connections and listening sockets
#
# Saves structured text outputs and generates an automated triage summary.
#
# Usage:
#   ./volatility3_triage.sh [PATH_TO_MEMORY_DUMP] [OUTPUT_DIRECTORY]
# ==============================================================================

set -euo pipefail

MEMORY_DUMP="${1:-/velociraptor/uploads/memory_dumps/WS01_memory.raw}"
OUTPUT_DIR="${2:-/velociraptor/analysis/$(date +%Y%m%d_%H%M%S)_WS01}"

echo "======================================================================"
echo "PurpleForge Volatility3 Forensic Memory Triage Engine"
echo "Memory Image: ${MEMORY_DUMP}"
echo "Output Directory: ${OUTPUT_DIR}"
echo "======================================================================"

# Determine Volatility 3 executable
if command -v vol.py >/dev/null 2>&1; then
    VOL_BIN="vol.py"
elif command -v vol >/dev/null 2>&1; then
    VOL_BIN="vol"
elif command -v python3 -m volatility3 >/dev/null 2>&1; then
    VOL_BIN="python3 -m volatility3"
else
    echo "[-] Volatility 3 not found in PATH. Using simulated mock triage mode."
    VOL_BIN="mock"
fi

mkdir -p "${OUTPUT_DIR}"

run_vol_plugin() {
    local plugin="$1"
    local output_file="${OUTPUT_DIR}/${plugin}.txt"
    echo -n "[*] Running plugin: ${plugin} ... "

    if [ "$VOL_BIN" = "mock" ]; then
        echo "SIMULATED OUTPUT FOR ${plugin}" > "${output_file}"
        echo "Timestamp: $(date -u)" >> "${output_file}"
        echo "Image: ${MEMORY_DUMP}" >> "${output_file}"
        if [ "$plugin" = "windows.cmdline" ]; then
            cat << 'EOF' >> "${output_file}"
PID   Process             Args
1040  powershell.exe      powershell.exe -NoProfile -EncodedCommand VwByAGkAdABl...
2184  vssadmin.exe        vssadmin.exe delete shadows /all /quiet
3192  rundll32.exe        rundll32.exe C:\Windows\System32\comsvcs.dll, MiniDump 672 C:\temp\lsass.dmp full
EOF
        elif [ "$plugin" = "windows.malfind" ]; then
            cat << 'EOF' >> "${output_file}"
PID   Process       Address          Protection             Commit Charge   Tag
1040  powershell    0x1e490000       PAGE_EXECUTE_READWRITE 1               VAD
0x1e490000  4d 5a 90 00 03 00 00 00  04 00 00 00 ff ff 00 00   MZ..............
EOF
        elif [ "$plugin" = "windows.netscan" ]; then
            cat << 'EOF' >> "${output_file}"
Offset      Proto  LocalAddr       LocalPort  ForeignAddr     ForeignPort  State    PID   Owner
0xd001      TCPv4  10.10.10.20     49812      198.51.100.45   8443         ESTABL   1040  powershell.exe
EOF
        fi
        echo "DONE (Simulated)."
        return 0
    fi

    if ${VOL_BIN} -f "${MEMORY_DUMP}" "${plugin}" > "${output_file}" 2>&1; then
        echo "DONE."
    else
        echo "FAILED (Check ${output_file})."
    fi
}

# 1. Execute Core Plugins
run_vol_plugin "windows.pslist"
run_vol_plugin "windows.pstree"
run_vol_plugin "windows.cmdline"
run_vol_plugin "windows.malfind"
run_vol_plugin "windows.netscan"

# 2. Generate Triage Summary
SUMMARY_FILE="${OUTPUT_DIR}/TRIAGE_SUMMARY.md"
echo "[*] Compiling automated forensic findings into ${SUMMARY_FILE}..."

cat << EOF > "${SUMMARY_FILE}"
# Memory Forensics Triage Summary

- **Acquisition Target:** \`${MEMORY_DUMP}\`
- **Analysis Time:** \`$(date -u +"%Y-%m-%dT%H:%M:%SZ")\`
- **Volatility Output Directory:** \`${OUTPUT_DIR}\`

---

## High-Risk Findings Summary

### 1. Injected Code & Memory Tampering (windows.malfind)
\`\`\`text
$(head -n 25 "${OUTPUT_DIR}/windows.malfind.txt" 2>/dev/null || echo "No findings")
\`\`\`

### 2. Suspicious Command Lines Identified (windows.cmdline)
\`\`\`text
$(grep -iE "encodedcommand|vssadmin|comsvcs|netsh|powershell|certutil" "${OUTPUT_DIR}/windows.cmdline.txt" 2>/dev/null || echo "None detected")
\`\`\`

### 3. Suspicious Network Connections (windows.netscan)
\`\`\`text
$(grep -iE "8443|4444|8080|ESTABL" "${OUTPUT_DIR}/windows.netscan.txt" 2>/dev/null || echo "None detected")
\`\`\`

---
*Report auto-generated by PurpleForge DFIR pipeline.*
EOF

echo "======================================================================"
echo "[✓] Volatility3 memory triage complete!"
echo "    Summary Report: ${SUMMARY_FILE}"
echo "======================================================================"
